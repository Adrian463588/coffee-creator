package com.coffeecreator.app.core.data

import android.content.Context
import android.content.Intent
import com.coffeecreator.app.core.model.CoffeeBean
import com.coffeecreator.app.core.model.Recipe
import com.google.gson.GsonBuilder

/**
 * Deterministic offline recipe export formatters and Android Sharesheet integration.
 * Zero network dependencies.
 */
object RecipeExportFormatter {
    private const val CARD_BORDER_WIDTH = 44
    private const val FAHRENHEIT_SCALE = 9.0
    private const val FAHRENHEIT_DIVISOR = 5.0
    private const val FAHRENHEIT_OFFSET = 32.0

    private val prettyGson = GsonBuilder().setPrettyPrinting().create()

    fun exportToJson(recipe: Recipe): String = prettyGson.toJson(recipe)

    fun exportToBaristaCard(recipe: Recipe, bean: CoffeeBean? = null): String = buildString {
        appendLine("☕ COFFEE CREATOR — RECIPE SPECIFICATION")
        appendLine("═".repeat(CARD_BORDER_WIDTH))
        appendLine("Recipe: ${recipe.name} (Rev v${recipe.version})")
        appendLine("Method: ${recipe.brewMethod}")
        if (recipe.equipment.isNotBlank()) appendLine("Equipment: ${recipe.equipment}")
        if (bean != null) {
            appendLine("Bean: ${bean.name}")
            appendLine("Origin: ${bean.country} (${bean.region}) · ${bean.process} · ${bean.roastLevel}")
        }
        appendLine("─".repeat(CARD_BORDER_WIDTH))
        appendLine("FORMULATION PARAMETERS:")
        appendLine("  • Dose:        ${recipe.doseGrams} g")
        appendLine(
            "  • Water:       ${recipe.waterGrams} g (Ratio ${recipe.targetRatio.ifBlank {
                "1:%.2f".format(
                    java.util.Locale.US,
                    recipe.waterGrams / recipe.doseGrams
                )
            }})"
        )
        appendLine(
            "  • Temperature: ${recipe.temperatureCelsius} °C (${"%.1f".format(
                java.util.Locale.US,
                (recipe.temperatureCelsius * FAHRENHEIT_SCALE / FAHRENHEIT_DIVISOR) + FAHRENHEIT_OFFSET
            )} °F)"
        )
        if (recipe.pressureBars != null) appendLine("  • Pressure:    ${recipe.pressureBars} bar")
        if (recipe.grindSize.isNotBlank()) appendLine("  • Grind Setup: ${recipe.grindSize}")
        if (recipe.grinderModel != null) appendLine("  • Grinder:     ${recipe.grinderModel} (${recipe.grinderSetting.orEmpty()})")
        if (recipe.firstDropSeconds != null) appendLine("  • First Drop:  ${recipe.firstDropSeconds} s")
        if (recipe.bypassGrams > 0) appendLine("  • Bypass:      ${recipe.bypassGrams} g")

        if (recipe.brewSteps.isNotEmpty()) {
            appendLine("─".repeat(CARD_BORDER_WIDTH))
            appendLine("ORDERED BREW STEPS:")
            recipe.brewSteps.forEach { step ->
                val valve = if (!step.valveStatus.isNullOrBlank()) " [Valve: ${step.valveStatus}]" else ""
                val temp = if (step.temperatureCelsius != null) " @ ${step.temperatureCelsius}°C" else ""
                appendLine(
                    "  [Step ${step.stepNumber}] ${step.action}: +${step.targetWaterGrams}g " +
                        "(Cum: ${step.cumulativeMassGrams}g) · ${step.durationSeconds}s$temp$valve"
                )
                if (step.description.isNotBlank()) {
                    appendLine("    → ${step.description}")
                }
            }
        }

        if (recipe.measuredTdsPercent != null && recipe.beverageMassGrams != null) {
            val ey = (recipe.beverageMassGrams * recipe.measuredTdsPercent) / recipe.doseGrams
            appendLine("─".repeat(CARD_BORDER_WIDTH))
            appendLine("MEASURED EXTRACTION LAB:")
            appendLine("  • Beverage Mass: ${recipe.beverageMassGrams} g")
            appendLine("  • Measured TDS:  ${recipe.measuredTdsPercent} %")
            appendLine("  • Approx EY:     ${"%.2f".format(java.util.Locale.US, ey)} %")
        }

        if (recipe.notes.isNotBlank()) {
            appendLine("─".repeat(CARD_BORDER_WIDTH))
            appendLine("NOTES: ${recipe.notes}")
        }
        appendLine("═".repeat(CARD_BORDER_WIDTH))
        appendLine("Offline-generated by Coffee Creator (coffee-science/2.0.0)")
    }

    fun shareRecipe(context: Context, recipe: Recipe, bean: CoffeeBean? = null, formatJson: Boolean = false) {
        val text = if (formatJson) exportToJson(recipe) else exportToBaristaCard(recipe, bean)
        val mimeType = if (formatJson) "application/json" else "text/plain"
        val sendIntent = Intent(Intent.ACTION_SEND).apply {
            type = mimeType
            putExtra(Intent.EXTRA_TEXT, text)
            putExtra(Intent.EXTRA_SUBJECT, "Coffee Recipe: ${recipe.name}")
            putExtra(Intent.EXTRA_TITLE, "Share ${recipe.name}")
        }
        val chooser = Intent.createChooser(sendIntent, "Share Recipe via")
        chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        context.startActivity(chooser)
    }

    fun shareJournalCsv(context: Context, csvContent: String) {
        val sendIntent = Intent(Intent.ACTION_SEND).apply {
            type = "text/csv"
            putExtra(Intent.EXTRA_TEXT, csvContent)
            putExtra(Intent.EXTRA_SUBJECT, "Coffee Creator — Brew Journal Export.csv")
            putExtra(Intent.EXTRA_TITLE, "Export Brew Journal CSV")
        }
        val chooser = Intent.createChooser(sendIntent, "Export Brew Journal CSV via")
        chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        context.startActivity(chooser)
    }
}
